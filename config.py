"""
Модуль глобальной конфигурации приложения Amagi-Player.
Централизует управление путями файловой системы, параметрами интеграции
с внешними P2P-клиентами и флагами верификации контента.
"""

import os
from dotenv import load_dotenv

# --- НАСТРОЙКИ ФАЙЛОВОЙ СИСТЕМЫ ---
# Автоматически определяем абсолютный путь к корневой директории проекта
BASE_DIR = os.path.dirname(os.path.abspath(__file__))

# Путь к локальному файлу базы данных SQLite (Data Layer)
DB_PATH = os.path.join(BASE_DIR, "data", "app_data.db")

# Директория для локального кэширования графических ассетов (постеров) с Кинопоиска
CACHE_DIR = os.path.join(BASE_DIR, "data", "cache")


# --- АРХИТЕКТУРА ВАЛИДАЦИИ КОНТЕНТА (ВАНТЛИСТ) ---
# Главный тумблер безопасности для стадии бета-тестирования.
# True  -> Строгий режим: разрешен запуск только тех фильмов, что внесены в базу верифицированного фонда.
# False -> Административный/тестовый режим: отключение проверок, разрешен запуск любых P2P-ссылок.
USE_WHITELIST = True


# --- ПАРАМЕТРЫ СВЯЗИ СО ВСТРОЕННЫМ QBITTORRENT ---
# Локальный URL-адрес фонового WebUI-сервера торрент-клиента
QBIT_URL = "http://localhost:8080"

# Аутентификационные данные по умолчанию для встроенного Portable-клиента
QBIT_USER = "admin"
QBIT_PASSWORD = "adminadmin"


# --- ИНТЕГРАЦИЯ С ВНЕШНИМИ API ---
# Автоматически считываем секретный токен из локального файла .env (если он существует)
load_dotenv(os.path.join(BASE_DIR, ".env"))

# Записываем токен в константу. Если файла .env нет, возвращается пустая строка,
# что переводит сервис Кинопоиска в отказоустойчивый автономный режим (только названия).
KP_API_KEY = os.getenv("KP_API_KEY", "")
