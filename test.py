"""
Скрипт изолированного тестирования корректности инициализации
глобальной конфигурации Amagi-Player.
"""

import os
import config

def run_config_test():
    print("=" * 60)
    print("ТЕСТИРОВАНИЕ ПОДСИСТЕМЫ КОНФИГУРАЦИИ")
    print("=" * 60)

    # Тест 1: Проверка корректности определения корневой папки
    print(f"[ТЕСТ 1] Корневая директория: {config.BASE_DIR}")
    assert os.path.isabs(config.BASE_DIR), "Ошибка: Путь к проекту должен быть абсолютным!"
    print(" -> Успешно.")

    # Тест 2: Проверка работы путей базы данных
    print(f"[ТЕСТ 2] Целевой путь к SQLite: {config.DB_PATH}")
    # Проверяем, что путь ведет именно в подпапку data
    assert "data" in config.DB_PATH, "Ошибка: Файл БД должен располагаться в папке data!"
    print(" -> Успешно.")

    # Тест 3: Проверка считывания API ключа (имитируем поведение системы)
    print("[ТЕСТ 3] Проверка отказоустойчивости API-ключа...")
    if not config.KP_API_KEY:
        print(" -> Ключ отсутствует (ОК: Система перейдет в автономный текстовый режим).")
    else:
        print(f" -> Ключ успешно считан: {config.KP_API_KEY[:4]}... (замаскировано)")

    print("\n" + "=" * 60)
    print("РЕЗУЛЬТАТ: Конфигурационный шаблон успешно прошел верификацию!")
    print("=" * 60)

if __name__ == "__main__":
    run_config_test()
